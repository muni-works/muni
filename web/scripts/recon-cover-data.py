#!/usr/bin/env python3
"""paper/recon/data/cover -> web/src/components/blog/covers/simCoverData.ts and web/public/research/sim-cover/

The Seeing Is Measuring cover. irys `recon_v1 render --cover` renders one test part, in the view of
one of its photographs, as the photograph's own part, without its loose holes and counterbores, and
with each alternative alone; irys `scripts/recon_cover_frames.py` crops those frames and their
residuals against the photograph (frames/). irys `recon_amp d` runs the amplitude fit on that part's
three photographs and records every accepted step (amp-d-<seed>.json). This script joins them: the
frames the cover blends, the amplitudes it replays and the program it writes. Nothing is drawn by hand.

  recon-cover-data.py <seed>
"""
import json, os, shutil, sys

seed = sys.argv[1] if len(sys.argv) > 1 else "3003"
here = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(here, "../../paper/recon/data/cover")
F = f"{D}/frames-{seed}"
pub = os.path.join(here, "../public/research/sim-cover")
os.makedirs(pub, exist_ok=True)
c = json.load(open(f"{D}/{seed}-cover.json"))
fr = json.load(open(f"{F}/frames.json"))
t = json.load(open(f"{D}/amp-d-{seed}.json"))
assert [o["kind"] for o in c["options"]] == t["extra"]["kinds"], "the renders and the fit disagree on the alternatives"
for n in os.listdir(F):
    if n.endswith((".png", ".jpg")):
        shutil.copyfile(f"{F}/{n}", f"{pub}/{n}")

r1 = lambda v: [round(x, 1) for x in v]
fmt = lambda xs: " ".join(f"{x:.2f}" for x in xs)
final_a, final_theta = t["a"], t["options"]
groups = []
for gi, g in enumerate(t["extra"]["groups"]):
    opts = []
    for k in g:
        th = final_theta[k]
        kind = c["options"][k]["kind"]
        dim = {"d": round(2 * th[2], 2)} if kind == "hole" else {"d": round(2 * th[3], 2), "depth": round(th[4], 2)}
        opts.append({"k": k, "kind": kind, "dim": dim, "line": f"{kind} {fmt(th)}"})
    o0 = c["options"][g[0]]
    groups.append({"centre": r1(o0["centre"]), "rim": [r1(p) for p in o0["rim"]], "box": fr["boxes"][gi], "options": opts})

steps = [{"beta": 0, "a": t["extra"]["a0"]}]
for s in t["trace"]:
    a = [round(x, 4) for x in s["a"]]
    if max(abs(x - y) for x, y in zip(a, steps[-1]["a"])) >= 0.004:
        steps.append({"beta": s["beta"], "a": a})
fa = [round(x, 4) for x in final_a]
if steps[-1]["a"] != fa:
    steps.append({"beta": t["trace"][-1]["beta"], "a": fa})

# the fitted base and boss, from the program the fit emitted (not the truth)
def two(line):
    w = line.split()
    return " ".join([w[0]] + [f"{float(x):.2f}" if x.replace(".", "", 1).replace("-", "", 1).isdigit() else x for x in w[1:]])
base_lines = [two(l) for l in t["emitted"].split("\n") if l.strip() and l.split()[0] not in ("hole", "counterbore", "pose")]
out = {
    "seed": int(seed), "size": c["size"], "groups": groups, "steps": steps, "base": base_lines,
    "nSteps": len(t["trace"]), "evals": t["evals"], "topologyOk": t["extra"]["topology_ok"], "gain": fr["gain"],
}
with open(os.path.join(here, "../src/components/blog/covers/simCoverData.ts"), "w") as f:
    f.write("// Generated by web/scripts/recon-cover-data.py from paper/recon/data/cover (irys recon_v1 render --cover,\n")
    f.write("// scripts/recon_cover_frames.py, recon_amp d): one test part's frames and its recorded fit. Don't edit by hand.\n")
    f.write("export const SIM_COVER = " + json.dumps(out) + " as const;\n")
print(f"part {seed}: {len(groups)} features, {len(steps)} frames of {len(t['trace'])} steps, final a {final_a}, topology {t['extra']['topology_ok']}")
