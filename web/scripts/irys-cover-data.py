#!/usr/bin/env python3
"""paper/irys/data/scene -> web/src/components/blog/covers/irysCoverData.ts

Every joint of rose full as irys's paper_hero projected it through the cover render's camera
(pivot, ±80 mm of axis, a 120 mm range-of-motion arc over its limits), the parts it moves
and limits from vcad hardware/rose-full/rose-full.joints.json. Run after paper_hero.
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
S = os.path.join(here, "../../paper/irys/data/scene")
rows = [l.rstrip("\n").split("\t") for l in open(f"{S}/annotation.tsv") if l.strip()]
inv = json.load(open(f"{S}/rose-full.joints.json"))
size = [float(x) for x in rows[0][1:3]]
arcs = {r[1]: r for r in rows if r[0] == "arc"}
joints = []
for r in rows:
    if r[0] != "joint" or "nan" in r[2:8]:
        continue
    f = [round(float(x), 1) for x in r[2:8]]
    a = arcs[r[1]]
    pts = [round(float(x), 1) for x in a[6:]]
    arc = [[pts[i], pts[i + 1]] for i in range(0, len(pts), 2) if pts[i] == pts[i] and pts[i + 1] == pts[i + 1]]
    joints.append({"name": r[1], "parent": a[2], "child": a[3], "lim": [float(a[4]), float(a[5])], "p": f[0:2], "a": f[2:4], "b": f[4:6], "arc": arc})
parts = sum(len(l["parts"]) for l in inv["links"].values())
# parts each joint moves: everything in its child link's subtree
kids = {}
for j in inv["joints"]:
    kids.setdefault(j["parent"], []).append(j["child"])
def subtree(l):
    return len(inv["links"].get(l, {}).get("parts", [])) + sum(subtree(c) for c in kids.get(l, []))
moves = {j["name"]: subtree(j["child"]) for j in inv["joints"]}
for j in joints:
    j["moves"] = moves[j["name"]]
out = os.path.join(here, "../src/components/blog/covers/irysCoverData.ts")
open(out, "w").write(
    "// Generated by web/scripts/irys-cover-data.py from paper/irys/data/scene (irys examples/paper_hero):\n"
    "// rose full's joints through the cover render's camera, in that render's pixels. Don't edit by hand.\n"
    f"export const IRYS_COVER = {json.dumps({'size': size, 'joints': joints, 'nJoints': len(inv['joints']), 'nParts': parts})} as const;\n")
print(f"{len(joints)} joints -> {out}")
